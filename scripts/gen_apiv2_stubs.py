#!/usr/bin/env python3
"""
Generate a type stub (.pyi) for pcs.cli.common.api_v2 from COMMAND_MAP.

ApiV2CommandProxy is a dynamic proxy: attribute access builds up a dotted
command name and calling it dispatches to the daemon. That makes it opaque to
mypy and IDEs. This script introspects COMMAND_MAP (the source of truth for the
APIv2 command set) and emits a stub describing a nested-class structure so that
e.g. `lib.apiv2.resource.create(...)` is type-checked against the real lib
command signature (minus the leading `env` parameter, which the daemon
supplies).

Usage:
    PYTHONPATH=<built-tree> python3 scripts/gen_apiv2_stubs.py [OUTPUT.pyi]

The package must be importable, which requires a configured tree (pcs/settings.py
generated from settings.py.in). With no argument the stub is written next to the
module it describes. Output is deterministic so it can be committed and checked
for staleness in CI.
"""

import inspect
import os
import sys
import types
import typing

# Make the stub independent of where the script lives relative to the package.
_HERE = os.path.dirname(os.path.abspath(__file__))
_DEFAULT_OUTPUT = os.path.join(
    _HERE, os.pardir, "pcs", "cli", "common", "api_v2.pyi"
)

HEADER = (
    "# This file is generated by scripts/gen_apiv2_stubs.py from COMMAND_MAP.\n"
    "# Do not edit by hand. Regenerate with `make gen-apiv2-stubs`.\n"
)


def _render_origin(origin: typing.Any, imports: set[str]) -> str:
    if isinstance(origin, type):
        if origin.__module__ == "builtins":
            return origin.__qualname__
        imports.add(origin.__module__)
        return f"{origin.__module__}.{origin.__qualname__}"
    imports.add("typing")
    return "typing.Any"


def _render_type(annotation: typing.Any, imports: set[str]) -> str:
    """Render a resolved annotation object to a fully-qualified type string."""
    if annotation is None or annotation is type(None):
        return "None"
    if annotation is Ellipsis:
        return "..."
    if annotation is typing.Any:
        imports.add("typing")
        return "typing.Any"

    origin = typing.get_origin(annotation)
    if origin is not None:
        args = typing.get_args(annotation)
        if origin is typing.Union or origin is types.UnionType:
            return " | ".join(_render_type(a, imports) for a in args)
        origin_str = _render_origin(origin, imports)
        if not args:
            return origin_str
        rendered_args = ", ".join(_render_type(a, imports) for a in args)
        return f"{origin_str}[{rendered_args}]"

    # typing.NewType instances expose __supertype__ and a real module/name.
    if hasattr(annotation, "__supertype__"):
        imports.add(annotation.__module__)
        return f"{annotation.__module__}.{annotation.__name__}"

    if isinstance(annotation, type):
        if annotation.__module__ == "builtins":
            return annotation.__qualname__
        imports.add(annotation.__module__)
        return f"{annotation.__module__}.{annotation.__qualname__}"

    # Unknown construct - stay safe rather than emit something uncheckable.
    imports.add("typing")
    return "typing.Any"


def _render_method_params(
    parameters: typing.Sequence[inspect.Parameter], imports: set[str]
) -> list[str]:
    parts = []
    for param in parameters:
        if param.name == "self":
            parts.append("self")
            continue
        if param.annotation is inspect.Parameter.empty:
            # This should not happen and lib commands should be properly typed
            # But there are still "old" lib commands that don't have type
            # annotations
            imports.add("typing")
            type_str = "typing.Any"
        else:
            type_str = _render_type(param.annotation, imports)

        rendered = f"{param.name}: {type_str}"
        if param.default is not inspect.Parameter.empty:
            rendered += " = ..."
        parts.append(rendered)

    return parts


def _render_method(
    name: str, qualified_name: str, cmd: typing.Any, imports: set[str]
) -> str:
    try:
        signature = inspect.signature(cmd.cmd, eval_str=True)
    except Exception as exc:
        # eval_str resolves string annotations against the command's module
        # globals. A name that only exists under `if TYPE_CHECKING:` (or any
        # other unresolvable forward reference) raises here. Surface the
        # offending command instead of a bare traceback from deep inside
        # inspect, so the fix is obvious.
        func = getattr(cmd, "cmd", cmd)
        module = getattr(func, "__module__", "<unknown module>")
        raise RuntimeError(
            f"cannot resolve the signature of command '{qualified_name}' "
            f"({module}.{getattr(func, '__qualname__', func)}): {exc}. "
            "If an annotation refers to a name imported only under "
            "`if TYPE_CHECKING:`, import it unconditionally so it resolves "
            "at runtime."
        ) from exc

    # Drop the first parameter - it is the LibraryEnvironment, supplied by the
    # daemon, never by the caller going through the proxy.
    params = list(signature.parameters.values())[1:]
    rendered_params = ["self"]
    if params:
        # The proxy forwards everything as **kwargs, so every argument is
        # keyword-only from the caller's point of view.
        rendered_params += ["*", *_render_method_params(params, imports)]

    if signature.return_annotation is inspect.Signature.empty:
        # This should not happen and lib commands should be properly typed
        # But there are still "old" lib commands that don't have type
        # annotations
        return_str = "None"
    else:
        return_str = _render_type(signature.return_annotation, imports)

    return f"    def {name}({', '.join(rendered_params)}) -> {return_str}: ..."


def _render_init(proxy_class: type, imports: set[str]) -> str:
    """Render the proxy class's real __init__ signature as a stub method.

    The root stub class stands in for the actual proxy object, so callers
    construct it directly. Introspecting the live signature keeps the stub in
    sync with the proxy's constructor instead of hardcoding its parameters.
    """
    signature = inspect.signature(proxy_class.__init__, eval_str=True)  # type: ignore [misc]
    parts = _render_method_params(list(signature.parameters.values()), imports)
    return f"    def __init__({', '.join(parts)}) -> None: ..."


def _class_name(path: tuple[str, ...], root_class: str) -> str:
    if not path:
        return root_class
    # Double-underscore joiner keeps names distinct even when a single segment
    # itself contains underscores (e.g. "cluster_property").
    return "_Ns_" + "__".join(path)


def _build_tree(command_map: typing.Any) -> dict:
    """Nested dict: segment -> sub-dict (namespace) or _Cmd (leaf command)."""
    tree: dict = {}
    for dotted_name, cmd in command_map.items():
        *namespace, leaf = dotted_name.split(".")
        node = tree
        for segment in namespace:
            existing = node.setdefault(segment, {})
            if not isinstance(existing, dict):
                raise ValueError(
                    f"'{dotted_name}' conflicts with command '{segment}'"
                )
            node = existing
        if leaf in node:
            raise ValueError(
                f"'{dotted_name}' conflicts with namespace '{leaf}'"
            )
        node[leaf] = cmd
    return tree


def _emit_classes(
    path: tuple[str, ...],
    node: dict,
    imports: set[str],
    out: list[str],
    proxy_class: type,
) -> None:
    """Emit child classes first (deepest first), then this node's class."""
    namespaces = {k: v for k, v in node.items() if isinstance(v, dict)}
    commands = {k: v for k, v in node.items() if not isinstance(v, dict)}

    for name in sorted(namespaces):
        _emit_classes(
            path + (name,), namespaces[name], imports, out, proxy_class
        )

    lines = [f"class {_class_name(path, proxy_class.__name__)}:"]
    if path == ():
        lines.append(_render_init(proxy_class, imports))

    lines.extend(
        f"    {name}: {_class_name(path + (name,), proxy_class.__name__)}"
        for name in sorted(namespaces)
    )
    lines.extend(
        _render_method(
            name,
            ".".join(path + (name,)),
            commands[name],
            imports,
        )
        for name in sorted(commands)
    )

    if len(lines) == 1:
        lines.append("    ...")
    out.append("\n".join(lines))


def generate_stub(command_map: typing.Any, proxy_class: type) -> str:
    tree = _build_tree(command_map)
    imports: set[str] = set()
    class_blocks: list[str] = []
    _emit_classes((), tree, imports, class_blocks, proxy_class)

    import_lines = "\n".join(f"import {module}" for module in sorted(imports))
    body = "\n\n".join(class_blocks)
    return f"{HEADER}\n{import_lines}\n\n\n{body}\n"


def main() -> None:
    from pcs.cli.common.api_v2 import ApiV2CommandProxy
    from pcs.daemon.async_tasks.worker.command_mapping import COMMAND_MAP

    output_path = sys.argv[1] if len(sys.argv) > 1 else _DEFAULT_OUTPUT
    stub = generate_stub(COMMAND_MAP, ApiV2CommandProxy)
    with open(output_path, "w", encoding="utf-8") as stub_file:
        stub_file.write(stub)


if __name__ == "__main__":
    main()
